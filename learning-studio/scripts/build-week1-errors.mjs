// Generates src/week1/learn/commonErrors.generated.ts: the "Common errors" boxes of the Week 1 textbook (spec LRN-04).
// Each chapter quotes the misconceptions that docs/week1/WEEK1_TEXTBOOK_IA.md §2 lists for it ("Errors" lines), taken
// verbatim from the faculty notes (`notes.misconceptions`) of the Week 1 lecture sources. The faculty notes stay where
// they are; the quoted pairs are copied here because the student edition strips every `notes` object
// (student-edition.ts). src/week1/learn/learn.test.tsx proves each pair still equals its source. Run: node scripts/build-week1-errors.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const app = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const ia = readFileSync(join(app, '..', 'docs', 'week1', 'WEEK1_TEXTBOOK_IA.md'), 'utf8')
const pairs = []
for (const f of ['session1.ts', 'session2.ts']) {
  const file = join(app, 'src', 'content', 'lectures', 'week01', f)
  const sf = ts.createSourceFile(file, readFileSync(file, 'utf8'), ts.ScriptTarget.Latest, true, ts.ScriptKind.TS)
  const visit = (n) => {
    if (ts.isPropertyAssignment(n) && ts.isIdentifier(n.name) && n.name.text === 'misconceptions' && ts.isArrayLiteralExpression(n.initializer)) {
      for (const el of n.initializer.elements) {
        if (!ts.isObjectLiteralExpression(el)) continue
        const get = (k) => {
          const p = el.properties.find((x) => ts.isPropertyAssignment(x) && x.name.text === k)
          return p && (ts.isStringLiteral(p.initializer) || ts.isNoSubstitutionTemplateLiteral(p.initializer)) ? p.initializer.text : null
        }
        pairs.push({ claim: get('claim'), correction: get('correction'), file: f, line: sf.getLineAndCharacterOfPosition(el.getStart()).line + 1 })
      }
    }
    ts.forEachChild(n, visit)
  }
  visit(sf)
}
const chapters = {}
let ch = null
for (const line of ia.split('\n')) {
  const h = line.match(/^### Chapter (\d+)\./)
  if (h) ch = `ch${h[1].padStart(2, '0')}`
  if (/^### Back matter/.test(line)) ch = null
  if (ch && /^- \*\*Errors/.test(line)) {
    const claims = [...line.matchAll(/"([^"]+)"|“([^”]+)”/g)].map((m) => m[1] ?? m[2]).filter((c) => !/^ENT/.test(c))
    chapters[ch] = claims.map((c) => {
      const norm = (s) => s.replace(/[’‘'“”"]/g, "'").replace(/\s+/g, ' ').trim()
      const key = norm(c).replace(/[.:;,!?]+$/, '')
      const hit = pairs.find((p) => p.claim && norm(p.claim) === norm(c)) ?? pairs.find((p) => p.claim && norm(p.claim).startsWith(key))
      if (!hit) throw new Error(`${ch}: no faculty misconception with the claim “${c}”`)
      return hit
    })
  }
}
const out = [
  '// GENERATED by scripts/build-week1-errors.mjs from the Week 1 faculty notes (notes.misconceptions) and the chapter',
  '// assignment in docs/week1/WEEK1_TEXTBOOK_IA.md §2. Do not edit by hand. Quoted, not moved: the notes keep their copy.',
  'export type CommonError = { claim: string; correction: string; source: string }',
  '',
  'export const COMMON_ERRORS: Record<string, CommonError[]> = ' + JSON.stringify(Object.fromEntries(Object.entries(chapters).map(([k, v]) => [k, v.map((p) => ({ claim: p.claim, correction: p.correction, source: `${p.file}:${p.line}` }))])), null, 2),
  '',
].join('\n')
writeFileSync(join(app, 'src', 'week1', 'learn', 'commonErrors.generated.ts'), out)
console.log(Object.entries(chapters).map(([k, v]) => `${k}: ${v.length}`).join(', '))
