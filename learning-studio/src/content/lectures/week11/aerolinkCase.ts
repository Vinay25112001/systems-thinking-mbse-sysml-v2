// AeroLink Week 11 case: the instructor's worked example of modeling the physical architecture and the interfaces
// (DECISION_LOG A21 decision 9: AeroLink is the instructor reference only; every team models its own enterprise). One
// module, read by the Week 11 lecture (both sessions), its figures, the worked-examples page and the tests.
//
// Single sources, read-only: AeroLink model v0.3 (../week10/aerolinkCase.ts AEROLINK_W10_MODEL, itself generated from
// model v0.2 and the Phase I package), the Week 4 case (physical elements, functions with their placement, information
// items with their producers and consumers, AI capabilities, externals), the Week 5 case (components, interfaces with their
// ends, crossings, media and constraints, interface requirements, externals' dispositions) and the Week 3 case (the
// technical performance measures whose current best estimates are the design values of the satisfy claims). Nothing is
// retyped: every name, statement, end, crossing and requirement is read from those modules. What this module adds is the
// instructor's MODELING DECISIONS (which Week 9 placeholder each physical element specializes, the item each physical
// crossing becomes, the functions that realize each interface requirement, the satisfy claims), the data a team enters in
// the lab tool.
//
// Model v0.4 is GENERATED by the lab tool's generator (src/workbench/week11/physical.ts) and kept as
// sysml/lectures/week11/aerolink_physical_interfaces_v04.sysml, which the course checker validates (week11-report.json).
// AeroLink Urban Mobility is FICTIONAL: every number, name and statement is a teaching value.
