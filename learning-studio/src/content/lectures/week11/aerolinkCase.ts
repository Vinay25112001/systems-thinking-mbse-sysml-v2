/** Week 4 also recorded, for each logical element, the physical elements it is allocated to (LOGICAL.phys). Model v0.4
 *  derives the allocation from the functions each element performs; this compares the two, so a difference is shown, not
 *  hidden (aerolinkCase.test.ts checks it). */
export const W4_ALLOCATION_CHECK = LOGICAL.map((l) => {
  const derived = G.allocations.filter((a) => a.log === l.id).map((a) => a.phy).sort()
  const w4 = [...l.phys].sort()
  return { log: l.id, name: l.name, w4, derived, onlyW4: w4.filter((p) => !derived.includes(p)), onlyDerived: derived.filter((p) => !w4.includes(p)) }
})
export const W4_ALLOCATION_DIFFS = W4_ALLOCATION_CHECK.filter((x) => x.onlyW4.length || x.onlyDerived.length)
