/** The thread of one function through the four behavior–structure links (Session 2): a scenario step subsets it, a
 *  logical part performs it, a state does it, a part exhibits that state. */
export const THREAD = (() => {
  const fn = 'FN-005'
  const step = FLOW_NODES.find((n) => n.kind === 'step' && n.construct.endsWith(fn))?.name ?? ''
  const state = MACHINE.states.find((s) => s.do === fn)?.name ?? ''
  return { fn, name: fnOf(fn).name, step, performer: performerOf(fn), performerName: LOGICAL.find((l) => l.id === performerOf(fn))?.name ?? '', state, exhibitor: MACHINE.exhibitor }
})()

