/** The declaration with short name <'id'> in a SysML text (header line and brace-matched body). */
export function declarationOf(text: string, id: string): string {
  const at = text.indexOf(`<'${id}'>`)
  if (at < 0) throw new Error(`no declaration of ${id}`)
  const start = text.lastIndexOf('\n', at) + 1
  const brace = text.indexOf('{', at)
  const semi = text.indexOf(';', at)
  if (brace < 0 || (semi >= 0 && semi < brace)) return text.slice(start, semi + 1)
  let depth = 0
  for (let i = brace; i < text.length; i++) {
    if (text[i] === '{') depth++
    else if (text[i] === '}' && --depth === 0) return text.slice(start, i + 1)
  }
  throw new Error(`unbalanced declaration of ${id}`)
}
/** Removes the common leading tabs of a block and shortens over-long documentation lines for a slide. */
export function tidy(block: string, maxDoc = 0): string[] {
  const lines = block.replace(/\r/g, '').split('\n')
  const lead = Math.min(...lines.filter((l) => l.trim()).map((l) => l.match(/^\t*/)![0].length))
  return lines.map((l) => {
    let t = l.slice(lead).replace(/\t/g, '    ')
    if (maxDoc && t.includes('doc /*') && t.length > maxDoc) t = `${t.slice(0, t.indexOf('doc /*') + 7)}… */${t.includes('*/') ? t.slice(t.lastIndexOf('*/') + 2) : ''}`
    return t
  })
}

