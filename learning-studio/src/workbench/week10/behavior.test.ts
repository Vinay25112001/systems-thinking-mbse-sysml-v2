// Week 10 generator (behavior.ts), both directions: the three readers accept the team's own files and refuse, with a
// reason the student can act on, a JSON file in the model field, a Markdown file, a Week 8 model v0.1, AeroLink, and a
// Week 2 file in the Week 4 field and the reverse; a generated model v0.3 imported again gives the same text; new IDs
// continue after the highest the Week 4 issued counter, the Week 4 IDs and the model text have used, and are never
// reused; every finding appears when its cause is present and disappears when it is removed; the flow writes a merge
// for a loop rejoin, done for an ending alternate and no decision when the scenario has no alternate; reachability is
// computed; each kind of exhibitor puts the exhibit in the right place. Uses the fictional food bank fixture.
import { describe, expect, it } from 'vitest'
import { AEROLINK_W9_MODEL } from '../../content/lectures/week09/aerolinkCase'
import { fixture9 } from '../week9/generated'
import { fixtureModel } from '../week8/generated'
import { FIXTURE10_CHOICES, FIXTURE_WEEK2_JSON, FIXTURE_WEEK4_JSON, fixture10, stress10 } from './generated'
import { dispositionProblem, generateModel, nextId, readWeek2For10, readWeek4For10, readWeek9, stripGenerated, type W10Choices } from './behavior'

const base = () => fixture10()
const gen = (patch: Partial<W10Choices>) => {
  const f = base()
  return generateModel(f.w9, f.arch, f.ops, { ...FIXTURE10_CHOICES, ...patch })
}
const codes = (g: { findings: { code: string; id: string }[] }) => g.findings.map((x) => `${x.code}:${x.id}`)

describe('readers: accept the team’s files, refuse the wrong ones with a reason', () => {
  it('the fixture files are read', () => {
    expect('model' in readWeek9(fixture9().model.text)).toBe(true)
    expect('record' in readWeek4For10(FIXTURE_WEEK4_JSON)).toBe(true)
    expect('record' in readWeek2For10(FIXTURE_WEEK2_JSON)).toBe(true)
  })
  it('model field: JSON, Markdown, a Week 8 model v0.1 and AeroLink are refused', () => {
    expect(readWeek9(FIXTURE_WEEK4_JSON)).toEqual({ error: expect.stringMatching(/JSON file/) })
    expect(readWeek9('# team-07: needs-to-requirements trace matrix\n\n| Need | Name |\n|---|---|\n')).toEqual({ error: expect.stringMatching(/Markdown/) })
    expect(readWeek9(fixtureModel().model.text)).toEqual({ error: expect.stringMatching(/model v0\.1/) })
    expect(readWeek9(AEROLINK_W9_MODEL.text)).toEqual({ error: expect.stringMatching(/AeroLink/) })
    expect(readWeek9('just text')).toEqual({ error: expect.stringMatching(/not a SysML v2 model file/) })
  })
  it('a deleted Behavior package is refused with what to restore', () => {
    const t = fixture9().model.text.replace(/\tpackage Behavior \{[\s\S]*?\n\t\}\n/, '')
    expect(readWeek9(t)).toEqual({ error: expect.stringMatching(/no top-level Behavior package/) })
  })
  it('Week 2 file in the Week 4 field and the reverse, and text that is not JSON', () => {
    expect(readWeek4For10(FIXTURE_WEEK2_JSON)).toEqual({ error: expect.stringMatching(/Week 2 model-inputs file: import it in the Week 2 field/) })
    expect(readWeek2For10(FIXTURE_WEEK4_JSON)).toEqual({ error: expect.stringMatching(/Week 4 model-inputs file: import it in the Week 4 field/) })
    expect(readWeek4For10('package X {}')).toEqual({ error: expect.stringMatching(/not valid JSON/) })
    expect(readWeek4For10('{"format":"week3-model-inputs"}')).toEqual({ error: expect.stringMatching(/Week 3 file/) })
  })
})

describe('re-import and IDs', () => {
  it('a generated model v0.3 imported again gives exactly the same text (nothing duplicated)', () => {
    const s = stress10()
    expect(s.model.text).toBe(s.first.text)
    const f = base()
    const first = generateModel(f.w9, f.arch, f.ops, FIXTURE10_CHOICES)
    const again = readWeek9(first.text)
    if ('error' in again) throw new Error(again.error)
    expect(generateModel(again.model, f.arch, f.ops, FIXTURE10_CHOICES).text).toBe(first.text)
    expect(first.text.split("action <'FN-001'>").length).toBe(2)
  })
  it('stripGenerated removes only the Week 10 regions; the Week 9 regions stay', () => {
    const t = stripGenerated(base().model.text)
    expect(t).not.toContain('generated by the Week 10 lab tool')
    expect(t).toContain('generated by the Week 9 lab tool')
  })
  it('the next ID is one past the highest of the Week 4 counter, the Week 4 IDs, the model text and the issued mark', () => {
    const f = base()
    expect(nextId('FN', f.arch, f.w9, 0)).toBe('FN-011')
    expect(nextId('INFO', f.arch, f.w9, 0)).toBe('INFO-006')
    expect(nextId('FN', { ...f.arch, issuedFn: 14 }, f.w9, 0)).toBe('FN-015')
    expect(nextId('FN', f.arch, { ...f.w9, maxFn: 20 }, 0)).toBe('FN-021')
    expect(nextId('FN', f.arch, f.w9, 30)).toBe('FN-031')
    expect(nextId('FN', f.arch, f.w9, 0, ['FN-011', 'FN-012'])).toBe('FN-013')
    expect(nextId('FN', null, null, 0)).toBe('FN-001')
  })
  it('a function added this week keeps its ID in the file and is reported as issued', () => {
    const g = base().model
    expect(g.text).toContain("action <'FN-011'> 'Move stock to the backup freezer'")
    expect(g.issued).toEqual(expect.arrayContaining(['FN-011', 'INFO-006']))
  })
})

describe('findings appear with their cause and go away when it is removed', () => {
  it('a function with no items is a gap; giving it an input removes it', () => {
    expect(codes(base().model)).toContain('fn-no-items:FN-004')
    expect(codes(gen({ fn: { ...FIXTURE10_CHOICES.fn, 'FN-004': { inputs: 'INFO-001', outputs: '', performer: '' } } }))).not.toContain('fn-no-items:FN-004')
  })
  it('an unknown item or performer is a defect and is left out of the text', () => {
    const g = gen({ fn: { ...FIXTURE10_CHOICES.fn, 'FN-001': { inputs: 'INFO-099', outputs: '', performer: 'LOG-099' } } })
    expect(codes(g)).toEqual(expect.arrayContaining(['item-missing-INFO-099:FN-001', 'performer-missing:FN-001']))
    expect(g.text).not.toContain("'INFO-099'")
    expect(g.functions.find((x) => x.id === 'FN-001')!.performer).toBe('')
  })
  it('an unallocated system requirement is a trace finding; the allocation writes allocate', () => {
    const f = base()
    expect(f.model.findings.filter((x) => x.code === 'req-unallocated')).toEqual([])
    expect(f.model.text).toMatch(/allocate Requirements::'REQ-SYS-00\d' to 'FN-0\d\d';/)
    const arch = { ...f.arch, functions: f.arch.functions.map((x) => ({ ...x, requirements: [] })) }
    const g = generateModel(f.w9, arch, f.ops, FIXTURE10_CHOICES)
    expect(g.findings.filter((x) => x.code === 'req-unallocated').map((x) => x.id)).toEqual(f.w9.requirements.filter((x) => x.startsWith('REQ-SYS-')))
  })
  it('a Week 9 placeholder linked to an element is specialized; an unlinked one is a gap', () => {
    expect(base().model.text).toContain("part def 'Route planning' :> 'Routing tool'")
    const g = gen({ placeholders: { ...FIXTURE10_CHOICES.placeholders, 'Routing tool': '' } })
    expect(codes(g)).toContain('placeholder-unlinked:Routing tool')
  })
  it('an actor that matches nothing is a gap until its type is given', () => {
    expect(codes(gen({ actors: {} }))).toContain('actor-unmapped:SCN-002')
    expect(codes(base().model)).not.toContain('actor-unmapped:SCN-002')
  })
  it('no scenario chosen is a gap, and no flow is written', () => {
    const g = gen({ scenario: '' })
    expect(codes(g)).toContain('no-scenario:SCENARIO')
    expect(g.flow).toBeNull()
  })
})

describe('the action flow', () => {
  it('a loop rejoin gets a merge before its step; an ending alternate ends at done', () => {
    const t = base().model.text
    const flow = t.slice(t.indexOf('first start;'), t.indexOf('// Item flows'))
    expect(flow).toMatch(/then decide afterDetectTemperatureRise;\n\t+if districtPowerCut then recordDistrictOutage;\n\t+else sendAlarm;/)
    expect(flow).toMatch(/action recordDistrictOutage \{[^\n]*\}\n\t+then done;/)
    expect(flow).toMatch(/action sendAlarm :> Logical::'FN-006'[^\n]*\n\t+then merge rejoinAcknowledgeAndTravel;\n\t+then action acknowledgeAndTravel/)
    expect(flow).toMatch(/action escalateToManager \{[^\n]*\}\n\t+then rejoinAcknowledgeAndTravel;/)
    expect(t).toContain('flow detectTemperatureRise.freezerTemperatures to sendAlarm.freezerTemperatures;')
    expect(base().model.flow).toMatchObject({ decisions: 2 })
  })
  it('a scenario without alternates has no decision (a gap) and ends with then done', () => {
    const f = base()
    const ops = { ...f.ops, scenarios: f.ops.scenarios.map((s) => (s.id === 'SCN-002' ? { ...s, alternates: [] } : s)) }
    const g = generateModel(f.w9, f.arch, ops, FIXTURE10_CHOICES)
    expect(g.flow?.decisions).toBe(0)
    expect(codes(g)).toContain('no-decision:SCN-002')
    expect(g.text).not.toContain('decide after')
    expect(g.text).toMatch(/then action moveStock[^\n]*\n\t+then done;/)
  })
  it('a guard written as “not name” keeps the negation; a guard that is not a name is reported', () => {
    expect(codes(gen({ alts: { ...FIXTURE10_CHOICES.alts, A2: { name: '', guard: 'x > 3' } } }))).toContain('guard-unreadable-A2:SCN-002')
    expect(gen({ alts: { ...FIXTURE10_CHOICES.alts, A2: { name: '', guard: 'not gridUp' } } }).text).toContain('if not gridUp then')
  })
})

describe('states: reachability, minimums and exhibitors', () => {
  const m = FIXTURE10_CHOICES.machine
  it('every fixture state is reachable; an added state no transition enters is a gap', () => {
    expect(base().model.machine?.unreachable).toEqual([])
    const g = gen({ machine: { ...m, states: [...m.states, { name: 'defrosting', entry: '', do: '', doc: '' }] } })
    expect(g.machine?.unreachable).toEqual(['defrosting'])
    expect(codes(g)).toContain('state-unreachable:defrosting')
  })
  it('below the minimums is a gap; a transition to a missing state is a defect', () => {
    const g = gen({ machine: { ...m, transitions: m.transitions.slice(0, 2).concat([{ from: 'cold', trigger: 'X', guard: '', to: 'nowhere' }]) } })
    expect(codes(g)).toEqual(expect.arrayContaining(['machine-minimum:STATES', 'transition-state-missing-cold-nowhere:STATES']))
    expect(codes(base().model)).not.toContain('machine-minimum:STATES')
  })
  it('two transition rows with the same blank states get distinct finding codes (unique keys)', () => {
    const blank = { from: '', trigger: 'X', guard: '', to: '' }
    const g = gen({ machine: { ...m, transitions: [...m.transitions, blank, blank, blank] } })
    const c = codes(g).filter((x) => x.startsWith('transition-state-missing--'))
    expect(c).toEqual(['transition-state-missing--:STATES', 'transition-state-missing---2:STATES', 'transition-state-missing---3:STATES'])
    expect(new Set(codes(g)).size).toBe(codes(g).length)
  })
  it('a logical element exhibits inside its part usage; the system of interest and a Physical definition get the exhibit in Physical', () => {
    const lt = base().model.text
    expect(lt).toMatch(/part <'LOG-004'> [^\n]*\{[^}]*exhibit Behavior::freezerStates;/)
    const soi = gen({ machine: { ...m, exhibitor: 'soi' } })
    expect(soi.machine?.exhibitedBy).toBe('soi')
    const soiBody = soi.text.slice(soi.text.indexOf('part soi :'), soi.text.indexOf('\n\t\t}', soi.text.indexOf('part soi :')))
    expect(soiBody).toContain('exhibit Behavior::freezerStates;')
    const def = gen({ machine: { ...m, exhibitor: 'Warehouse and cold storage' } })
    expect(def.text).toMatch(/part def 'Warehouse and cold storage'[\s\S]*?exhibit Behavior::freezerStates;/)
    const bad = gen({ machine: { ...m, exhibitor: 'Nowhere' } })
    expect(codes(bad)).toEqual(expect.arrayContaining(['exhibitor-missing:Nowhere', 'no-exhibitor:STATES']))
    expect(bad.text).not.toContain('exhibit Behavior::')
  })
})

describe('dispositions', () => {
  it('short plans are accepted; empty answers and claimed fixes are refused', () => {
    for (const ok of ['Open item: Week 11 (JS)', 'Kept: a role inside the enterprise', 'To be resolved in Week 11, owner AK', 'Closed site at night: no function', 'Done-by date is Week 11 (owner JS)']) expect(dispositionProblem(ok), ok).toBeNull()
    for (const bad of ['', 'none', 'n/a todo', 'tbd, later']) expect(dispositionProblem(bad), bad).toMatch(/not a disposition/)
    for (const claim of ['Fixed', 'Resolved in the Week 4 record', 'Done', 'Done.', 'It is closed now', 'We corrected it']) expect(dispositionProblem(claim), claim).toMatch(/reads as a fix/)
  })
})

describe('review fixes (Week 10 review M2, N1, N2, m2, m3, m6)', () => {
  it('M2: a decision sits after its step by default, or before it when the team says the condition is known first', () => {
    const after = gen({}).text
    expect(after).toMatch(/action acknowledgeAndTravel[^\n]*\n\t*then decide afterAcknowledgeAndTravel;/)
    const g = gen({ alts: { ...FIXTURE10_CHOICES.alts, A1: { ...FIXTURE10_CHOICES.alts.A1, at: 'before' } } })
    // before step 3: the merge (A1 rejoins at 3), then the decision, whose else is the step itself
    expect(g.text).toMatch(/merge rejoinAcknowledgeAndTravel;\n\t*then decide beforeAcknowledgeAndTravel;\n\t*if noAcknowledgementIn15Min then escalateToManager;\n\t*else acknowledgeAndTravel;/)
    expect(g.text).not.toMatch(/afterAcknowledgeAndTravel/)
    expect(g.flow!.nodes.find((n) => n.kind === 'decide' && n.name === 'beforeAcknowledgeAndTravel')!.conops).toMatch(/^before step 3/)
    expect(g.flow!.decisions).toBe(2)
  })
  it('N2: a function with no output, or no input, is a gap needing a disposition; with neither, the both-sides gap', () => {
    const g = gen({ fn: { ...FIXTURE10_CHOICES.fn, 'FN-009': { inputs: 'INFO-004', outputs: '', performer: '' }, 'FN-010': { inputs: '', outputs: 'INFO-003', performer: '' }, 'FN-004': { inputs: '', outputs: '', performer: '' } } })
    expect(codes(g)).toEqual(expect.arrayContaining(['fn-no-output:FN-009', 'fn-no-input:FN-010', 'fn-no-items:FN-004']))
    expect(codes(g)).not.toContain('fn-no-output:FN-004')
    const ok = gen({ fn: { ...FIXTURE10_CHOICES.fn, 'FN-009': { inputs: 'INFO-004', outputs: 'INFO-003', performer: '' } } })
    expect(codes(ok)).not.toContain('fn-no-output:FN-009')
  })
  it('N1: a team of three need not give items to the functions its chosen scenario does not use; a team of four must', () => {
    const f = base()
    const three = generateModel(f.w9, { ...f.arch, threePersonTeam: true }, f.ops, { ...FIXTURE10_CHOICES, fn: { ...FIXTURE10_CHOICES.fn, 'FN-009': { inputs: 'INFO-004', outputs: '', performer: '' } } })
    expect(codes(three)).toContain('fn-items-later:FN-009')
    expect(codes(three)).not.toContain('fn-no-output:FN-009')
    // a function the scenario uses keeps its gap for a team of three
    const used = generateModel(f.w9, { ...f.arch, threePersonTeam: true }, f.ops, { ...FIXTURE10_CHOICES, fn: { ...FIXTURE10_CHOICES.fn, 'FN-006': { inputs: 'INFO-002', outputs: '', performer: '' } } })
    expect(codes(used)).toContain('fn-no-output:FN-006')
    expect(three.findings.find((x) => x.code === 'no-scenario')).toBeUndefined()
    expect(generateModel(f.w9, { ...f.arch, threePersonTeam: true }, f.ops, { ...FIXTURE10_CHOICES, scenario: '' }).findings.find((x) => x.code === 'no-scenario')!.text).toMatch(/team of three chooses any scenario/)
  })
  it('m2: the #derivedFrom keyword definition sits outside every Week 9 region, so the Week 9 tool keeps it when it re-reads v0.3', async () => {
    const { AEROLINK_W10_MODEL } = await import('../../content/lectures/week10/aerolinkCase')
    const { stripGenerated: strip9 } = await import('../week9/requirements')
    const kept = strip9(AEROLINK_W10_MODEL.text)
    expect(kept).toContain('metadata def <derivedFrom> DerivedFromLink')
    expect(kept).toContain('#derivedFrom dependency')
    // negative direction: inside a Week 9 region the definition would be stripped
    const inside = AEROLINK_W10_MODEL.text.replace('\t// --- generated by the Week 9 lab tool: end ---\n\t// --- generated by the Week 10 lab tool: begin ---\n\t// Course convention: a function or requirement', '\t// --- generated by the Week 10 lab tool: begin ---\n\t// Course convention: a function or requirement')
    expect(strip9(inside)).not.toContain('metadata def <derivedFrom> DerivedFromLink')
  })
  it('m3: the Week 9 sentence about capability links waiting is annotated with where Week 10 wrote them, and only in v0.3', async () => {
    const { AEROLINK_W10_MODEL } = await import('../../content/lectures/week10/aerolinkCase')
    expect(AEROLINK_W10_MODEL.text).toMatch(/Parent links to capabilities wait for Week 10[^\n]*\n\t*\/\/ --- generated by the Week 10 lab tool: begin ---\n\t*\/\/ Week 10: these capability links are written in the Logical package as #derivedFrom dependencies/)
    expect(stripGenerated(AEROLINK_W10_MODEL.text)).not.toContain('Week 10: these capability links')
  })
  it('m6: a Week 1 or Week 3 file in the Week 2 field is refused with the week named', () => {
    expect(readWeek2For10(JSON.stringify({ format: 'week1-model-inputs', version: 1 }))).toEqual({ error: expect.stringMatching(/This is a Week 1 file\. This field takes the Week 2 model-inputs file/) })
    expect(readWeek2For10(JSON.stringify({ format: 'week3-model-inputs', version: 1 }))).toEqual({ error: expect.stringMatching(/This is a Week 3 file/) })
  })
})
