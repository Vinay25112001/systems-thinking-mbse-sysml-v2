const readFile = (f: File) =>
  new Promise<string>((resolve, reject) => {
    const fr = new FileReader()
    fr.onload = () => resolve(String(fr.result ?? ''))
    fr.onerror = () => reject(fr.error)
    fr.readAsText(f)
  })

function Section({ id, title, children }: { id: string; title: string; children: ReactNode }) {
  return (
    <section aria-labelledby={`${id}-h`} className="w8-part" data-testid={id}>
      <h2 id={`${id}-h`} className="w8-ph">
        {title}
      </h2>
      <div className="w8-body">{children}</div>
    </section>
  )
}
function Scroll({ label, children }: { label: string; children: ReactNode }) {
  return (
    <div className="w8-scroll" tabIndex={0} role="region" aria-label={`${label} (scrolls sideways on small screens)`}>
      {children}
    </div>
  )
}

